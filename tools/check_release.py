#!/usr/bin/env python3
"""Stop a release while anything unconfirmed or unfinished is still in the public files.

Fails when README.md, CONTRIBUTING.md or docs/ contain a [[CONFIRM: ...]] marker, a TODO, an em dash,
an en dash, or a price. Also fails when data/ does not validate, or when docs/data.js is out of date
with data/.
Usage: python tools/check_release.py
Exit codes: 0 clean, 1 problems found.
Standard library only.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import validate  # noqa: E402

TARGETS = [ROOT / "README.md", ROOT / "CONTRIBUTING.md", ROOT / "docs"]
BAD = [("[[CONFIRM", "unconfirmed marker"), ("TODO", "TODO"), ("—", "em dash"), ("–", "en dash")]
PRICE_RE = re.compile(r"[$£€₹]\s?\d|\b\d[\d,.]*\s?(USD|EUR|GBP|INR|dollars)\b", re.I)
SUFFIXES = {".md", ".html", ".js", ".txt"}


def files():
    for t in TARGETS:
        if t.is_file():
            yield t
        elif t.is_dir():
            for p in sorted(t.rglob("*")):
                if p.is_file() and p.suffix in SUFFIXES:
                    yield p


def main():
    problems = 0
    for p in files():
        text = p.read_text(encoding="utf-8")
        for needle, label in BAD:
            if needle in text:
                line = next(i for i, ln in enumerate(text.splitlines(), 1) if needle in ln)
                print(f"{p.relative_to(ROOT)}:{line}: {label}")
                problems += 1
        m = PRICE_RE.search(text)
        if m:
            line = next(i for i, ln in enumerate(text.splitlines(), 1) if PRICE_RE.search(ln))
            print(f"{p.relative_to(ROOT)}:{line}: looks like a price ({m.group(0).strip()})")
            problems += 1

    models = json.loads((ROOT / "data" / "models.json").read_text(encoding="utf-8"))
    tiers = json.loads((ROOT / "data" / "hardware-tiers.json").read_text(encoding="utf-8"))
    for msg in validate.validate_models(models) + validate.validate_tiers(tiers):
        print("data: " + msg)
        problems += 1

    expected = "/* Generated by tools/build_site.py from data/. Do not edit. */\nwindow.WIR_DATA = " + json.dumps(
        {"models": models, "tiers": tiers}, indent=1, ensure_ascii=False) + ";\n"
    data_js = ROOT / "docs" / "data.js"
    if not data_js.exists() or data_js.read_text(encoding="utf-8") != expected:
        print("docs/data.js is missing or out of date: run python tools/build_site.py")
        problems += 1

    for required in ("README.md", "LICENSE", "CONTRIBUTING.md", "docs/index.html", "docs/engine.js", "docs/card.js"):
        if not (ROOT / required).exists():
            print(f"missing file: {required}")
            problems += 1
    readme = (ROOT / "README.md").read_text(encoding="utf-8") if (ROOT / "README.md").exists() else ""
    for heading in ("## Limits", "## How the verdict works"):
        if heading not in readme:
            print(f"README.md: missing section {heading}")
            problems += 1

    print(f"{problems} problems")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
