#!/usr/bin/env python3
"""Build docs/data.js from data/models.json and data/hardware-tiers.json.

The page reads window.WIR_DATA, so it works from file:// where fetch of a JSON file is blocked.
Runs validate.py first and refuses to build when it fails.
Usage: python tools/build_site.py
Exit codes: 0 built, 1 data failed validation.
Standard library only.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import validate  # noqa: E402


def main():
    models = json.loads((ROOT / "data" / "models.json").read_text(encoding="utf-8"))
    tiers = json.loads((ROOT / "data" / "hardware-tiers.json").read_text(encoding="utf-8"))
    problems = validate.validate_models(models) + validate.validate_tiers(tiers)
    if problems:
        for p in problems:
            print(p)
        print("Not building: fix the data first.")
        return 1
    payload = {"models": models, "tiers": tiers}
    text = "/* Generated by tools/build_site.py from data/. Do not edit. */\nwindow.WIR_DATA = " + json.dumps(payload, indent=1, ensure_ascii=False) + ";\n"
    (ROOT / "docs" / "data.js").write_text(text, encoding="utf-8", newline="\n")
    print("Built docs/data.js")
    return 0


if __name__ == "__main__":
    sys.exit(main())
